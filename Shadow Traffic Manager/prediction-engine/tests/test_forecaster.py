"""
Shadow Traffic — Forecasting Engine Unit Tests
Role in Architecture:
    Validates point estimates and calibrated confidence bounds generated by
    the DualForecaster across different time horizons and series lengths.
"""

from datetime import datetime, timezone, timedelta
from src.forecaster import DualForecaster


def test_forecast_confidence_interval_bounds():
    forecaster = DualForecaster(horizon_minutes=20, confidence_level=0.90)
    t0 = datetime(2026, 9, 21, 10, 0, 0, tzinfo=timezone.utc)

    # 15 observations with increasing trend
    series = [
        (t0 + timedelta(minutes=i), 100.0 + (i * 10.0))
        for i in range(15)
    ]

    fc = forecaster.forecast("request_rate", series, horizon_minutes=20)

    assert fc.metric_name == "request_rate"
    assert fc.horizon_minutes == 20
    # Expected value at t = 14 + 20 = 34 min -> ~100 + 340 = ~440 RPS
    assert fc.yhat > series[-1][1]
    assert fc.yhat_lower <= fc.yhat <= fc.yhat_upper
    assert fc.confidence_level == 0.90
    assert fc.model_used in ["prophet", "statsmodels"]


def test_forecast_short_series_graceful_handling():
    forecaster = DualForecaster(horizon_minutes=15)
    t0 = datetime(2026, 9, 21, 12, 0, 0, tzinfo=timezone.utc)

    # 2 observations (very sparse)
    series = [
        (t0, 45.0),
        (t0 + timedelta(minutes=1), 46.0),
    ]

    fc = forecaster.forecast("avg_response_time_ms", series)
    assert fc.yhat >= 40.0
    assert fc.yhat_lower <= fc.yhat <= fc.yhat_upper
    assert fc.model_used == "persistence"
